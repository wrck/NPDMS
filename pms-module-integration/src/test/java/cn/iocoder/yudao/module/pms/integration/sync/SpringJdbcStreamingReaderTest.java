    @Test void autoIncrementKeyOrderIsIndependentOfBusinessDatesAcrossChunks() throws Exception {
        String url="jdbc:h2:mem:primary_key_stream;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE";
        try(var connection=DriverManager.getConnection(url,"sa","");var statement=connection.createStatement()) {
            statement.execute("CREATE TABLE historical_source(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,happened INT)");
            statement.execute("INSERT INTO historical_source(happened) VALUES(10),(30),(20)");
        }
        var source=SyncDefinition.Source.builder().object("HISTORY").sourceObject("historical_source").readMode("TABLE")
                .table("historical_source").sourceKey("id").columns(List.of("id","happened")).filters(List.of()).build();
        var definition=SyncDefinition.builder().connectionId(1L).mode("ONCE").readStrategy("STREAMING_CURSOR")
                .chunkSize(1).maxRows(100).maxBytes(1024).sources(List.of(source)).build();
        var ids=new ArrayList<Long>();
        new SpringJdbcStreamingReader(sourceApi(url)).stream(definition,null,true,null,
                chunk->chunk.rows().forEach(row->ids.add(((Number)row.get("id")).longValue())));
        assertEquals(List.of(1L,2L,3L),ids);
    }
    @Test void nullableRevisionParameterBindsAndKeepsSqlNullInTheRow() throws Exception {
        var parameters = new java.util.LinkedHashMap<String,Object>();
        parameters.put("revision", null);
        var source = SyncDefinition.Source.builder().object("ITEM").sourceObject("revision_source").readMode("SQL")
                .sql("SELECT 1 AS id, CAST(:revision AS BIGINT) AS revisionId").parameters(parameters).sourceKey("id")
                .columns(List.of()).filters(List.of()).mappings(List.of()).build();
        var definition = SyncDefinition.builder().connectionId(1L).mode("ONCE").maxRows(10).maxBytes(10000)
                .sources(List.of(source)).build();
        var rows = new ArrayList<Map<String,Object>>();
        var result = new SpringJdbcStreamingReader(sourceApi("jdbc:h2:mem:nullable_revision;DATABASE_TO_LOWER=TRUE"))
                .stream(definition, null, true, null, chunk -> { if (!chunk.sourceComplete()) rows.addAll(chunk.rows()); });
        assertEquals(1, result.rows()); assertEquals(1, rows.size());
        assertTrue(rows.getFirst().containsKey("revisionid")); assertNull(rows.getFirst().get("revisionid"));
    }
    @Test void groupedSourceAndAliasUseOneCursorAndKeepOriginalIdsInTheSameChunk() throws Exception {
        String url="jdbc:h2:mem:grouped_stream;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE";
        var root=SyncDefinition.Source.builder().object("MASTER").sourceObject("header").readMode("SQL")
                .sql("SELECT 12 AS _groupkey, '[{\"object\":\"MASTER\",\"fields\":{\"id\":12}},{\"object\":\"ALIAS\",\"fields\":{\"oldId\":11}}]' AS _sourcerows")
                .sourceKey("id").groupKey("_groupkey").rowProjection("_sourcerows").parameters(Map.of()).build();
        var alias=SyncDefinition.Source.builder().object("ALIAS").sourceObject("original").readMode("SQL")
                .sourceKey("oldId").queryRef("MASTER").build();
        var definition=SyncDefinition.builder().connectionId(1L).mode("ONCE").maxRows(10).maxBytes(10000)
                .sources(List.of(root,alias)).build();
        var chunks=new ArrayList<List<MysqlSyncReader.SourceRows>>();
        new SpringJdbcStreamingReader(sourceApi(url)).stream(definition,null,true,null,chunk->{
            if(!chunk.sourceComplete())chunks.add(SyncSourceProjection.expand(new SyncSourceProjection.Input(definition,root,chunk.rows())));
        });
        assertEquals(1,chunks.size());assertEquals(2,chunks.getFirst().size());
        assertEquals(12,chunks.getFirst().getFirst().rows().getFirst().get("id"));
        assertEquals(11,chunks.getFirst().getLast().rows().getFirst().get("oldId"));
    }
