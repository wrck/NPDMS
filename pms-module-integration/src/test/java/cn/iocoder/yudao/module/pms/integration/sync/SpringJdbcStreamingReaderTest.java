    @Test void compositeRowsKeepDuplicatesAndNullsAcrossChunksWithoutInventedNativeKey() throws Exception {
        String url="jdbc:h2:mem:factory_composite_stream;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE";
        try(var connection=DriverManager.getConnection(url,"sa","");var statement=connection.createStatement()) {
            statement.execute("CREATE TABLE factory_source(sn VARCHAR(30),version VARCHAR(30))");
            statement.execute("INSERT INTO factory_source VALUES(NULL,'v1'),(NULL,'v1'),('A',NULL)");
        }
        var source=SyncDefinition.Source.builder().object("FACTORY").sourceObject("factory_source").readMode("TABLE")
                .table("factory_source").sourceKey("factoryRowKey").sourceKeyColumns(List.of("sn","version"))
                .columns(List.of("sn","version")).filters(List.of()).build();
        var definition=SyncDefinition.builder().connectionId(1L).mode("ONCE").readStrategy("STREAMING_CURSOR")
                .restartPolicy("RESTART_ALL").chunkSize(1).maxRows(1).maxBytes(1024).sources(List.of(source)).build();
        var keys=new ArrayList<String>();var rows=new ArrayList<Map<String,Object>>();
        new SpringJdbcStreamingReader(sourceApi(url)).stream(definition,null,true,null,chunk->{
            for(var row:chunk.rows()){keys.add(row.get("factoryRowKey").toString());rows.add(row);}
        });
        assertEquals(3,rows.size());assertEquals(3,new java.util.HashSet<>(keys).size());
        assertEquals(2,rows.stream().filter(row->row.get("sn")==null && "v1".equals(row.get("version"))).count());
    }
