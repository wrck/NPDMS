    private record DeliveryRead(String database,String values,String taskKey) {}
    private static void streamDelivery(DeliveryRead input,List<String> keys) throws Exception {
        String url="jdbc:h2:mem:"+input.database()+";DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE;CASE_INSENSITIVE_IDENTIFIERS=TRUE";
        try(var connection=DriverManager.getConnection(url,"sa","");var statement=connection.createStatement()) {
            statement.execute("CREATE TABLE delivery_source(seq BIGINT GENERATED BY DEFAULT AS IDENTITY, nativekey VARCHAR(30))");
            statement.execute("INSERT INTO delivery_source(nativekey) VALUES"+input.values());
        }
        var source=SyncDefinition.Source.builder().object("CONTRACT").sourceObject("pm_order_data_from_erp")
                .readMode("SQL").sql("SELECT nativekey AS \"_groupKey\", '[]' AS \"_sourceRows\" FROM delivery_source ORDER BY seq")
                .parameters(Map.of()).sourceKey("id").groupKey("_groupKey").rowProjection("_sourceRows")
                .columns(List.of()).filters(List.of()).mappings(List.of()).build();
        var definition=SyncDefinition.builder().adapter("TABLE_MAPPING").taskKey(input.taskKey()).sourceSystem("DPPMS").connectionId(1L)
                .mode("ONCE").readStrategy("STREAMING_CURSOR").restartPolicy("RESTART_ALL")
                .chunkSize(1).maxRows(1).maxBytes(1024).sources(List.of(source)).build();
        new SpringJdbcStreamingReader(sourceApi(url)).stream(definition,null,true,null,
                chunk->chunk.rows().forEach(row->keys.add(row.get("_groupKey").toString())));
    }

