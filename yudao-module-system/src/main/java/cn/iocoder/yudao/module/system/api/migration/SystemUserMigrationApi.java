package cn.iocoder.yudao.module.system.api.migration;

import tools.jackson.databind.JsonNode;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Set;

/** Formal account carry; credentials and login facts never cross the migration boundary. */
public interface SystemUserMigrationApi {
    /** Exact historical actor identity, including disabled users; never returns credentials. */
    record HistoricalIdentity(Long id, String username) {}
    List<HistoricalIdentity> getHistoricalIdentities(Long tenantId, Set<Long> userIds);
    /** Exact tenant account codes for historical business audit, including disabled users. */
    List<HistoricalIdentity> getHistoricalIdentitiesByUsername(Long tenantId, Set<String> usernames);
    /** 精确原账号的真实工号，不从登录名截取；不返回凭据或建立授权。 */
    record MemberIdentity(Long id, String username, String employeeNo) { }
    List<MemberIdentity> getHistoricalMemberIdentities(Long tenantId, Set<String> usernames);
    record Profile(String username, String nickname, String remark, Long departmentId, Set<Long> postIds,
                   String email, String mobile, Integer sex, String avatar, Integer status,
                   String employeeNo, JsonNode customInfo) {}
    record Audit(String creator, LocalDateTime createTime, String updater, LocalDateTime updateTime) {}
    /** Nonempty actors are exact source identity keys within this batch, including aliases. */
    record SourceAudit(String creatorIdentity, LocalDateTime createTime,
                       String updaterIdentity, LocalDateTime updateTime) {}
    record User(Long id, Profile profile, Audit audit) {}
    record Entry(String object, String sourceKey, Profile profile, SourceAudit audit, Long targetId,
                 User lastApplied, boolean referenceOnly, Long adjudicatedExistingId) {
        public String identity() { return object + ":" + sourceKey; }
    }
    /** Audit linkage only: never imports account attributes, roles, or authorization. */
    record AuditReference(String object, String sourceKey, Long userId, String expectedUsername, Long previousTargetId) {
        public String identity() { return object + ":" + sourceKey; }
    }
    record Request(Long tenantId, String owner, List<Entry> entries, boolean adoptExisting,
                   List<AuditReference> auditReferences) {
        public Request(Long tenantId, String owner, List<Entry> entries, boolean adoptExisting) {
            this(tenantId, owner, entries, adoptExisting, List.of());
        }
    }
    record Result(String object, String sourceKey, User before, User after, String action, String message) {}
    List<Result> preview(Request request);
    /** Joins the integration transaction that commits bindings and run evidence. */
    List<Result> apply(Request request);

    /** Explicit, reviewed correction of an updater wrongly generated by migration auto-fill. */
    record AuditCorrection(User expectedCurrent, User restored) {}
    record AuditCorrectionRequest(Long tenantId, String owner, String generatedUpdater, List<AuditCorrection> entries,
                                  LocalDateTime generatedUpdateFrom, LocalDateTime generatedUpdateTo) {
        public AuditCorrectionRequest(Long tenantId,String owner,String generatedUpdater,List<AuditCorrection> entries) {
            this(tenantId,owner,generatedUpdater,entries,null,null);
        }
    }
    record AuditCorrectionResult(User before, User after, String action) {}
    List<AuditCorrectionResult> previewAuditCorrection(AuditCorrectionRequest request);
    List<AuditCorrectionResult> applyAuditCorrection(AuditCorrectionRequest request);
}
