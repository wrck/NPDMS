CREATE TABLE `com_outbox_event` (
    `id` bigint NOT NULL,
    `event_id` varchar(64) NOT NULL,
    `event_type` varchar(64) NOT NULL,
    `aggregate_type` varchar(64) NOT NULL,
    `aggregate_key` varchar(128) NOT NULL,
    `scope_version` bigint NOT NULL,
    `payload` json NOT NULL,
    `status` varchar(32) NOT NULL,
    `occurred_at` datetime NOT NULL,
    `retry_count` int NOT NULL DEFAULT 0,
    `creator` varchar(64) DEFAULT '',
    `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updater` varchar(64) DEFAULT '',
    `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted` bit(1) NOT NULL DEFAULT b'0',
    `tenant_id` bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_com_outbox_event` (`tenant_id`, `event_id`),
    KEY `idx_com_outbox_dispatch` (`tenant_id`, `status`, `occurred_at`, `id`),
    CONSTRAINT `ck_com_outbox_status` CHECK (`status` IN ('PENDING', 'PUBLISHED', 'FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='商务域事务Outbox';
