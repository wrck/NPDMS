-- 撤销旧模板页面菜单及按钮权限的全部角色授权。
UPDATE `system_role_menu`
SET `deleted` = b'1',
    `updater` = 'system',
    `update_time` = NOW()
WHERE `menu_id` IN (18015, 18034, 18042, 18043)
  AND `deleted` = b'0';

-- 先停用并隐藏，再按基础平台逻辑删除语义退役旧模板页面菜单及其按钮权限。
UPDATE `system_menu`
SET `status` = 1,
    `visible` = b'0',
    `deleted` = b'1',
    `updater` = 'system',
    `update_time` = NOW()
WHERE `id` IN (18015, 18034, 18042, 18043)
  AND `deleted` = b'0';
