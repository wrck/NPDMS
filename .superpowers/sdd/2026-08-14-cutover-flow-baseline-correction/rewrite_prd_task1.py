def replace_section(text: str, start: str, end: str, replacement: str) -> str:
    pattern = rf"(?ms)^{re.escape(start)}\n.*?(?=^{re.escape(end)}\n)"
    updated, count = re.subn(pattern, replacement.rstrip() + "\n\n", text, count=1)
    if count != 1:
        raise RuntimeError(f"section replacement failed: {start} -> {end}, count={count}")
    return updated


def replace_once(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count != 1:
        raise RuntimeError(f"exact replacement failed: count={count}, old={old[:80]!r}")
    return text.replace(old, new, 1)


